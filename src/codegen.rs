/// Render the Rust field type for a role player, accounting for inferred
/// multiplicity. `Multiplicity::List` wraps the bare type in `Vec<T>`.
/// Prose role players (data type doesn't sanitise) still fall back to `()`.
fn role_player_field_type(rp: &crate::prepared::RolePlayerSpec) -> String {
    let bare = sanitize_rust_type(&rp.data_type);
    if bare == "()" {
        return "()".into();
    }
    match rp.multiplicity {
        crate::prepared::Multiplicity::List => format!("Vec<{}>", bare),
        crate::prepared::Multiplicity::Single => bare.to_string(),
    }
}

fn emit_role_player_field(out: &mut String, rp: &crate::prepared::RolePlayerSpec) {
    let snake = to_snake_case(&rp.name);
    let ty = role_player_field_type(rp);
    if ty == "()" {
        writeln!(out, "    {}: (), // {}", snake, rp.data_type).unwrap();
    } else {
        writeln!(out, "    {}: {},", snake, ty).unwrap();
    }
}

/// Compute the bare Rust type for an attribute — i.e. what goes into the
/// struct field, the constructor parameter, and the getter return (sans `&`)
/// before any multiplicity wrapping.
///
/// Default is `()`. When a tracker-preserved type is available (from a
/// prior `/implement` decision recorded in `.reen/build.json`), that type
/// wins. Multiplicity wrapping (`Vec<T>`) is applied separately by
/// [`attribute_full_type`].
fn attribute_bare_type(
    _attr: &crate::prepared::AttributeSpec,
    preserved: Option<&str>,
) -> String {
    match preserved {
        Some(ty) if !ty.is_empty() && ty != "()" => ty.to_string(),
        _ => "()".to_string(),
    }
}

/// Compute the full Rust type for an attribute: the bare type wrapped in
/// `Vec<…>` when multiplicity is `List`. Used by struct field, constructor
/// parameter, and getter return — keeping the three in lockstep so the
/// generated code compiles.
fn attribute_full_type(
    attr: &crate::prepared::AttributeSpec,
    preserved: Option<&str>,
) -> String {
    let bare = attribute_bare_type(attr, preserved);
    match attr.multiplicity {
        crate::prepared::Multiplicity::List => format!("Vec<{}>", bare),
        crate::prepared::Multiplicity::Single => bare,
    }
}

fn emit_attribute_field_with_preserved(
    out: &mut String,
    attr: &crate::prepared::AttributeSpec,
    preserved: Option<&str>,
) {
    let snake = to_snake_case(&attr.name);
    let ty = attribute_full_type(attr, preserved);
    let trailing = if preserved.is_some_and(|p| !p.is_empty() && p != "()") {
        format!(" // {}", attr.description)
    } else {
        format!(" // TODO: type to be filled by /implement — {}", attr.description)
    };
    writeln!(out, "    {}: {},{}", snake, ty, trailing).unwrap();
}

/// Render the full method signature line `    <vis> fn <name>(<recv>, <params>) -> <ret> {`.
/// When `sig` is None, falls back to `(&self)` returning unit.
fn emit_method_signature(
    out: &mut String,
    visibility: &str,
    method_name: &str,
    sig: Option<&crate::prepared::DerivedSignature>,
) {
    let prefix = if visibility.is_empty() {
        String::new()
    } else {
        format!("{} ", visibility)
    };
    match sig {
        Some(sig) => {
            let params: Vec<String> = sig
                .parameters
                .iter()
                .map(|p| format!("{}: {}", to_snake_case(&p.name), p.rust_type))
                .collect();
            let ret = if sig.returns == "()" {
                String::new()
            } else {
                format!(" -> {}", sig.returns)
            };
            let recv = if sig.receiver.is_empty() { "&self".into() } else { sig.receiver.clone() };
            let mut sig_line = format!("    {}fn {}({}", prefix, method_name, recv);
            for p in &params {
                sig_line.push_str(", ");
                sig_line.push_str(p);
            }
            sig_line.push(')');
            sig_line.push_str(&ret);
            sig_line.push_str(" {");
            writeln!(out, "{}", sig_line).unwrap();
        }
        None => {
            writeln!(out, "    {}fn {}(&self) {{", prefix, method_name).unwrap();
        }
    }
}

/// Projection functionalities are required to take `&self` (verifier rejects
/// `&mut self`). Strip an upgraded receiver from the derived signature so
/// the emitted method matches the kind contract.
fn projection_safe_signature(
    sig: Option<&crate::prepared::DerivedSignature>,
) -> Option<crate::prepared::DerivedSignature> {
    sig.map(|s| {
        let mut clone = s.clone();
        clone.receiver = "&self".into();
        clone
    })
}

/// Emit `use crate::data::<snake>::<T>;` lines for every unique referencable
/// data type appearing as a role player. Sorted alphabetically by type name.
/// Emits a trailing blank line if any imports were produced.
fn emit_data_type_imports(out: &mut String, role_players: &[RolePlayerSpec]) {
    let mut types: BTreeSet<String> = BTreeSet::new();
    for rp in role_players {
        let ty = sanitize_rust_type(&rp.data_type);
        if !is_referencable_data_type(ty) {
            continue;
        }
        types.insert(ty.to_string());
    }
    if types.is_empty() {
        return;
    }
    for ty in &types {
        writeln!(out, "use crate::data::{}::{};", to_snake_case(ty), ty).unwrap();
    }
    writeln!(out).unwrap();
}

/// True iff `ty` is a bare PascalCase type that should be imported from
/// `crate::data::<snake>`. Unit, primitives, qualified paths, and generic
/// shapes are filtered out.
fn is_referencable_data_type(ty: &str) -> bool {
    if ty.is_empty() || ty == "()" {
        return false;
    }
    if ty.contains("::") || ty.contains('<') || ty.contains('>') || ty.contains('(') || ty.contains(')') {
        return false;
    }
    if is_rust_primitive(ty) {
        return false;
    }
    // Must start with an ASCII uppercase letter — anything else is not a
    // PascalCase data-type identifier we want to import.
    ty.chars().next().map(|c| c.is_ascii_uppercase()).unwrap_or(false)
}

fn is_rust_primitive(ty: &str) -> bool {
    matches!(
        ty,
        "bool"
            | "char"
            | "str"
            | "String"
            | "i8"
            | "i16"
            | "i32"
            | "i64"
            | "i128"
            | "isize"
            | "u8"
            | "u16"
            | "u32"
            | "u64"
            | "u128"
            | "usize"
            | "f32"
            | "f64"
    )
}

fn role_player_type<'a>(artifact: &'a PreparedArtifact, role_name: &str) -> &'a str {
    artifact
        .role_players
        .iter()
        .find(|rp| rp.name == role_name)
        .map(|rp| sanitize_rust_type(&rp.data_type))
        .unwrap_or("()")
}

/// Return the data_type as-is if it looks like a valid Rust type identifier
/// (PascalCase name or path like `rand::rngs::ThreadRng`), otherwise return `()`.
fn sanitize_rust_type(data_type: &str) -> &str {
    let trimmed = data_type.trim();
    if trimmed.is_empty() {
        return "()";
    }
    // A valid Rust type is either a simple identifier (ascii-alphanumeric + _),
    // a path with `::`, or a generic with `<>`. If it contains spaces,
    // `@` (API refs), or `/` it's not a Rust type.
    if trimmed.contains(' ') || trimmed.contains('@') || trimmed.contains('/') {
        return "()";
    }
    trimmed
}

pub fn to_snake_case(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 4);
    let mut prev_was_lower = false;
    for ch in s.chars() {
        if ch.is_ascii_uppercase() {
            if prev_was_lower {
                out.push('_');
            }
            out.push(ch.to_ascii_lowercase());
            prev_was_lower = false;
        } else if ch == ' ' || ch == '-' {
            out.push('_');
            prev_was_lower = false;
        } else {
            out.push(ch);
            prev_was_lower = ch.is_ascii_lowercase();
        }
    }
    out
}

