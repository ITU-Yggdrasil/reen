fn scaffold_output_path(workspace: &Workspace, artifact: &PreparedArtifact) -> PathBuf {
    let subdir = match artifact.kind {
        ArtifactKind::Data => "data",
        ArtifactKind::Projection => "projections",
        ArtifactKind::Context => "contexts",
        // Phase 10 will add scaffold paths for web kinds
        ArtifactKind::Component => "components",
        ArtifactKind::Brand => "brand",
        ArtifactKind::RoutingTable => "routes",
        ArtifactKind::App => return workspace.root.join("src").join("main.rs"),
    };
    let filename = to_snake_case(&artifact.export.name);
    workspace
        .root
        .join("src")
        .join(subdir)
        .join(format!("{}.rs", filename))
}

pub fn generate_rust(artifact: &PreparedArtifact) -> String {
    match artifact.kind {
        ArtifactKind::Context => generate_context(artifact),
        ArtifactKind::Data => generate_data(artifact),
        ArtifactKind::Projection => generate_projection(artifact),
        // Phase 10 will add codegen for web kinds
        ArtifactKind::Component | ArtifactKind::Brand | ArtifactKind::RoutingTable => {
            String::new()
        }
        // App codegen is handled separately via generate_app_main
        ArtifactKind::App => String::new(),
    }
}

fn generate_context(a: &PreparedArtifact) -> String {
    let name = &a.export.name;
    let mut out = String::new();

    // Imports for any role players whose data type is a referencable
    // crate-local type. Without these the generated file does not compile —
    // role-method parameters and struct fields name the type unqualified.
    emit_data_type_imports(&mut out, &a.role_players);

    // Struct
    writeln!(out, "pub struct {} {{", name).unwrap();
    for rp in &a.role_players {
        emit_role_player_field(&mut out, rp);
    }
    for prop in &a.props {
        // Props are scalar config — we don't know the type, so use a placeholder
        writeln!(out, "    {}: (), // prop: {}", to_snake_case(&prop.name), prop.description).unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    // Impl
    writeln!(out, "impl {} {{", name).unwrap();

    // Public methods = functionalities (default to &self; implementer upgrades to &mut self)
    for func in &a.functionalities {
        writeln!(out, "    /// {}", func.description.lines().next().unwrap_or("")).unwrap();
        emit_method_signature(&mut out, "pub", &to_snake_case(&func.name), func.derived_signature.as_ref());
        writeln!(out, "        todo!()").unwrap();
        writeln!(out, "    }}").unwrap();
        writeln!(out).unwrap();
    }

    // Private methods = role methods (canonical names)
    for group in &a.role_methods {
        for rm in &group.methods {
            writeln!(out, "    /// Role method ({}.{}): {}", group.role, rm.name, rm.citation).unwrap();
            writeln!(
                out,
                "    fn {}(&self, {}_: &{}) {{",
                rm.canonical_name,
                to_snake_case(&group.role),
                role_player_type(a, &group.role)
            )
            .unwrap();
            writeln!(out, "        todo!()").unwrap();
            writeln!(out, "    }}").unwrap();
            writeln!(out).unwrap();
        }
    }

    writeln!(out, "}}").unwrap();
    out
}

fn generate_data(a: &PreparedArtifact) -> String {
    generate_data_with_preserved(a, &BTreeMap::new(), &BTreeMap::new())
}

fn generate_data_with_preserved(
    a: &PreparedArtifact,
    preserved_attr_types: &BTreeMap<String, String>,
    preserved_variant_attr_types: &BTreeMap<(String, String), String>,
) -> String {
    if !a.data_variants.is_empty() {
        return generate_variant_data_with_preserved(
            a,
            preserved_attr_types,
            preserved_variant_attr_types,
        );
    }

    let name = &a.export.name;
    let mut out = String::new();

    // Struct — every field private. The kind contract reserves access to the
    // generated getters; direct field access is a verify violation. The
    // STRUCT_MARKER on the line above is the anchor `extract_attribute_types`
    // uses to find the struct block.
    writeln!(out, "{}", STRUCT_MARKER).unwrap();
    writeln!(out, "pub struct {} {{", name).unwrap();
    for attr in &a.attributes {
        let preserved = preserved_attr_types
            .get(&to_snake_case(&attr.name))
            .map(String::as_str);
        emit_attribute_field_with_preserved(&mut out, attr, preserved);
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "impl {} {{", name).unwrap();

    // Mandatory new() constructor — body filled by /implement to enforce
    // every declared invariant and construct Self. Parameter types match
    // the struct field types so multiplicity-list fields take a Vec.
    let new_params: Vec<String> = a.attributes.iter()
        .map(|attr| {
            let preserved = preserved_attr_types
                .get(&to_snake_case(&attr.name))
                .map(String::as_str);
            format!("{}: {}", to_snake_case(&attr.name), attribute_full_type(attr, preserved))
        })
        .collect();
    writeln!(out, "    /// Construct a new {}, validating every invariant from the prepared YAML.", name).unwrap();
    writeln!(out, "    pub fn new({}) -> anyhow::Result<Self> {{", new_params.join(", ")).unwrap();
    writeln!(out, "        todo!(\"enforce invariants and construct\")").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out).unwrap();

    // Getters — one per declared attribute. Bodies are deterministic and
    // emitted fully; /implement does not touch them. Return type matches
    // the field type so `&self.<field>` typechecks for both `T` and `Vec<T>`.
    for attr in &a.attributes {
        let preserved = preserved_attr_types
            .get(&to_snake_case(&attr.name))
            .map(String::as_str);
        let field = to_snake_case(&attr.name);
        let ty = attribute_full_type(attr, preserved);
        writeln!(out, "    /// {}", attr.description.lines().next().unwrap_or("")).unwrap();
        writeln!(out, "    pub fn {}(&self) -> &{} {{", field, ty).unwrap();
        writeln!(out, "        &self.{}", field).unwrap();
        writeln!(out, "    }}").unwrap();
        writeln!(out).unwrap();
    }

    // Operations — split between non-destructive mutators (kind: with) and
    // ordinary read-only operations.
    for op in &a.operations {
        let op_name = to_snake_case(&op.name);
        if op.kind.as_deref() == Some("with") {
            // with_* signature: by-value self, returns Result<Self>.
            writeln!(out, "    /// {}", op.description.lines().next().unwrap_or("")).unwrap();
            writeln!(out, "    pub fn {}(self, value: ()) -> anyhow::Result<Self> {{", op_name).unwrap();
            writeln!(out, "        todo!(\"construct via Self::new with the field replaced\")").unwrap();
            writeln!(out, "    }}").unwrap();
            writeln!(out).unwrap();
        } else {
            writeln!(out, "    /// {}", op.description.lines().next().unwrap_or("")).unwrap();
            emit_method_signature(&mut out, "pub", &op_name, op.derived_signature.as_ref());
            writeln!(out, "        todo!()").unwrap();
            writeln!(out, "    }}").unwrap();
            writeln!(out).unwrap();
        }
    }

    writeln!(out, "}}").unwrap();
    out
}

/// Emit the wrapper-struct + `<Name>Kind` enum + `<Name>Payload` enum shape
/// for a sum-typed data draft. The `kind` shared attribute is special: its
/// type is `<Name>Kind` (derived from the variant list, not from prose), so
/// it does not appear in the per-attribute getter loop and is omitted from
/// the constructor parameters (the constructor derives the kind from the
/// payload variant tag).
fn generate_variant_data_with_preserved(
    a: &PreparedArtifact,
    preserved_attr_types: &BTreeMap<String, String>,
    preserved_variant_attr_types: &BTreeMap<(String, String), String>,
) -> String {
    let name = &a.export.name;
    let mut out = String::new();

    // Discriminator enum — exactly one variant per data_variant in source order.
    writeln!(out, "/// Variant discriminator for {}.", name).unwrap();
    writeln!(out, "#[derive(Debug, Clone, Copy, PartialEq, Eq)]").unwrap();
    writeln!(out, "pub enum {}Kind {{", name).unwrap();
    for v in &a.data_variants {
        writeln!(out, "    {},", to_pascal_case(&v.name)).unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    // Payload enum — per-variant fields. Per-variant attribute types come
    // from the tracker (or default to `()` with a TODO comment when /implement
    // hasn't picked one yet). The PAYLOAD_ENUM_MARKER on the line above is
    // the anchor `extract_variant_attribute_types` uses to find the enum
    // block.
    writeln!(out, "/// Variant payload for {}. Per-variant fields.", name).unwrap();
    writeln!(out, "{}", PAYLOAD_ENUM_MARKER).unwrap();
    writeln!(out, "pub enum {}Payload {{", name).unwrap();
    for v in &a.data_variants {
        let pascal = to_pascal_case(&v.name);
        if v.attributes.is_empty() {
            writeln!(out, "    {},", pascal).unwrap();
            continue;
        }
        writeln!(out, "    {} {{", pascal).unwrap();
        for attr in &v.attributes {
            let key = (v.name.clone(), to_snake_case(&attr.name));
            let preserved = preserved_variant_attr_types
                .get(&key)
                .map(String::as_str);
            let ty = attribute_full_type(attr, preserved);
            let trail = if preserved.is_some_and(|p| !p.is_empty() && p != "()") {
                String::new()
            } else {
                " // TODO: type to be filled by /implement".to_string()
            };
            writeln!(
                out,
                "        {}: {},{}",
                to_snake_case(&attr.name),
                ty,
                trail,
            ).unwrap();
        }
        writeln!(out, "    }},").unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    // Wrapper struct. The `kind` attribute (if declared) maps to `<Name>Kind`;
    // every other shared attribute uses the standard preserved-type path; a
    // mandatory `payload` field carries the variant payload. STRUCT_MARKER
    // on the line above is the anchor for `extract_attribute_types`.
    writeln!(out, "{}", STRUCT_MARKER).unwrap();
    writeln!(out, "pub struct {} {{", name).unwrap();
    let mut shared_non_kind: Vec<&AttributeSpec> = Vec::new();
    let mut has_kind = false;
    for attr in &a.attributes {
        if is_kind_attribute(&attr.name) {
            has_kind = true;
            writeln!(
                out,
                "    kind: {}Kind, // {}",
                name,
                attr.description,
            ).unwrap();
            continue;
        }
        let preserved = preserved_attr_types
            .get(&to_snake_case(&attr.name))
            .map(String::as_str);
        emit_attribute_field_with_preserved(&mut out, attr, preserved);
        shared_non_kind.push(attr);
    }
    if !has_kind {
        // No explicit `kind` attribute in the draft — synthesise the field
        // anyway so the discriminator is reachable.
        writeln!(out, "    kind: {}Kind, // synthesised variant discriminator", name).unwrap();
    }
    writeln!(out, "    payload: {}Payload,", name).unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "impl {} {{", name).unwrap();

    // Constructor — takes every shared non-kind attribute plus the payload.
    // The constructor derives `kind` from the payload variant tag, so the
    // caller does not pass it.
    let new_params: Vec<String> = shared_non_kind
        .iter()
        .map(|attr| {
            let preserved = preserved_attr_types
                .get(&to_snake_case(&attr.name))
                .map(String::as_str);
            format!(
                "{}: {}",
                to_snake_case(&attr.name),
                attribute_full_type(attr, preserved),
            )
        })
        .chain(std::iter::once(format!("payload: {}Payload", name)))
        .collect();
    writeln!(out, "    /// Construct a new {}, validating every invariant from the prepared YAML.", name).unwrap();
    writeln!(out, "    /// Derives `kind` from the payload variant tag — callers don't pass it.").unwrap();
    writeln!(out, "    pub fn new({}) -> anyhow::Result<Self> {{", new_params.join(", ")).unwrap();
    writeln!(out, "        todo!(\"enforce invariants and construct\")").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out).unwrap();

    // Kind getter — always emitted; references the wrapper field.
    writeln!(out, "    /// The variant discriminant.").unwrap();
    writeln!(out, "    pub fn kind(&self) -> &{}Kind {{", name).unwrap();
    writeln!(out, "        &self.kind").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out).unwrap();

    // Shared non-kind getters.
    for attr in &shared_non_kind {
        let preserved = preserved_attr_types
            .get(&to_snake_case(&attr.name))
            .map(String::as_str);
        let field = to_snake_case(&attr.name);
        let ty = attribute_full_type(attr, preserved);
        writeln!(out, "    /// {}", attr.description.lines().next().unwrap_or("")).unwrap();
        writeln!(out, "    pub fn {}(&self) -> &{} {{", field, ty).unwrap();
        writeln!(out, "        &self.{}", field).unwrap();
        writeln!(out, "    }}").unwrap();
        writeln!(out).unwrap();
    }

    // Payload getter — callers pattern-match on this for variant-specific data.
    writeln!(out, "    /// The variant payload — callers pattern-match for variant-specific data.").unwrap();
    writeln!(out, "    pub fn payload(&self) -> &{}Payload {{", name).unwrap();
    writeln!(out, "        &self.payload").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out).unwrap();

    // Operations — same shape as non-variant data emission.
    for op in &a.operations {
        let op_name = to_snake_case(&op.name);
        if op.kind.as_deref() == Some("with") {
            writeln!(out, "    /// {}", op.description.lines().next().unwrap_or("")).unwrap();
            writeln!(out, "    pub fn {}(self, value: ()) -> anyhow::Result<Self> {{", op_name).unwrap();
            writeln!(out, "        todo!(\"construct via Self::new with the field replaced\")").unwrap();
            writeln!(out, "    }}").unwrap();
            writeln!(out).unwrap();
        } else {
            writeln!(out, "    /// {}", op.description.lines().next().unwrap_or("")).unwrap();
            emit_method_signature(&mut out, "pub", &op_name, op.derived_signature.as_ref());
            writeln!(out, "        todo!()").unwrap();
            writeln!(out, "    }}").unwrap();
            writeln!(out).unwrap();
        }
    }

    writeln!(out, "}}").unwrap();
    out
}

fn is_kind_attribute(name: &str) -> bool {
    to_snake_case(name) == "kind"
}

/// `user_utterance` → `UserUtterance`, `confirmation_card_rejected` →
/// `ConfirmationCardRejected`. Used to map snake-cased variant names from
/// the prepared YAML into Rust enum variant identifiers.
pub fn to_pascal_case(name: &str) -> String {
    name.split(|c: char| c == '_' || c == '-' || c == ' ')
        .filter(|s| !s.is_empty())
        .map(|word| {
            let mut chars = word.chars();
            match chars.next() {
                Some(c) => format!("{}{}", c.to_uppercase(), chars.as_str()),
                None => String::new(),
            }
        })
        .collect()
}

fn generate_projection(a: &PreparedArtifact) -> String {
    // Projections emit identically to contexts, with two structural
    // constraints enforced by `reen verify`:
    //   * every functionality takes &self (never &mut self)
    //   * every role method takes its role player as & (never &mut)
    // The codegen path itself produces &self/`&` already; verify keeps
    // /implement edits honest.
    let name = &a.export.name;
    let mut out = String::new();

    // Imports for role-player data types — same reason as contexts.
    emit_data_type_imports(&mut out, &a.role_players);

    // Struct — private fields, one per role player and prop.
    writeln!(out, "pub struct {} {{", name).unwrap();
    for rp in &a.role_players {
        emit_role_player_field(&mut out, rp);
    }
    for prop in &a.props {
        writeln!(out, "    {}: (), // prop: {}", to_snake_case(&prop.name), prop.description).unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "impl {} {{", name).unwrap();

    // Constructor — projections expose a public new() that adapters call to
    // bind role players + props at construction time.
    if !a.role_players.is_empty() || !a.props.is_empty() {
        let params: Vec<String> = a.role_players.iter()
            .map(|rp| {
                let ty = role_player_field_type(rp);
                format!("{}: {}", to_snake_case(&rp.name), ty)
            })
            .chain(a.props.iter().map(|p| format!("{}: ()", to_snake_case(&p.name))))
            .collect();
        writeln!(out, "    /// Bind role players and props.").unwrap();
        writeln!(out, "    pub fn new({}) -> Self {{", params.join(", ")).unwrap();
        writeln!(out, "        todo!()").unwrap();
        writeln!(out, "    }}").unwrap();
        writeln!(out).unwrap();
    }

    // Functionalities — pub, always &self (immutable). Projection-specific
    // constraint: even when the derived signature suggests `&mut self`, the
    // verifier rejects it. We honour the derived shape only for params and
    // return type.
    for func in &a.functionalities {
        writeln!(out, "    /// {}", func.description.lines().next().unwrap_or("")).unwrap();
        let sig = projection_safe_signature(func.derived_signature.as_ref());
        emit_method_signature(&mut out, "pub", &to_snake_case(&func.name), sig.as_ref());
        writeln!(out, "        todo!()").unwrap();
        writeln!(out, "    }}").unwrap();
        writeln!(out).unwrap();
    }

    // Role methods — private, role player as & (never &mut).
    for group in &a.role_methods {
        for rm in &group.methods {
            writeln!(out, "    /// Role method ({}.{}): {}", group.role, rm.name, rm.citation).unwrap();
            writeln!(
                out,
                "    fn {}(&self, {}_: &{}) {{",
                rm.canonical_name,
                to_snake_case(&group.role),
                role_player_type(a, &group.role)
            )
            .unwrap();
            writeln!(out, "        todo!()").unwrap();
            writeln!(out, "    }}").unwrap();
            writeln!(out).unwrap();
        }
    }

    writeln!(out, "}}").unwrap();
    out
}

// ── Surgical (AST-aware) code generation ─────────────────────────

/// Generate Rust code for an artifact with tracker-aware body preservation.
///
/// For methods whose tracker entry is `fresh`, the body is preserved verbatim
/// from the existing source. For `stale` or `not_implemented` entries (or
/// entries not in the tracker), the body is `todo!()`.
fn generate_rust_surgical(
    artifact: &PreparedArtifact,
    tracker: &BuildTracker,
    existing_source: Option<&str>,
) -> String {
    // Extract preserved bodies from existing source
    let preserved = existing_source
        .map(|src| extract_method_bodies(src))
        .unwrap_or_default();

    match artifact.kind {
        ArtifactKind::Context => generate_context_surgical(artifact, tracker, &preserved),
        ArtifactKind::Data => {
            // Attribute Rust types are recovered from the existing struct
            // declaration when the tracker says they're still fresh — see
            // `attribute_types_from_tracker_and_source` for the gating rule.
            let attr_types = attribute_types_from_tracker_and_source(
                artifact,
                tracker,
                existing_source,
            );
            if !artifact.data_variants.is_empty() {
                let variant_attr_types = variant_attribute_types_from_tracker_and_source(
                    artifact,
                    tracker,
                    existing_source,
                );
                generate_variant_data_with_preserved(
                    artifact,
                    &attr_types,
                    &variant_attr_types,
                )
            } else {
                generate_data_surgical(artifact, tracker, &preserved, &attr_types)
            }
        }
        ArtifactKind::Projection => generate_projection_surgical(artifact, tracker, &preserved),
        _ => generate_rust(artifact),
    }
}

/// Decide which attribute Rust types from `existing_source` we're allowed to
/// preserve. The tracker's `data_attribute_type` entry per attribute decides:
/// `Fresh` → keep; `Stale` / `NotImplemented` / absent → drop (the field
/// reverts to `()` plus a TODO comment for `/implement`).
fn attribute_types_from_tracker_and_source(
    artifact: &PreparedArtifact,
    tracker: &BuildTracker,
    existing_source: Option<&str>,
) -> BTreeMap<String, String> {
    let Some(source) = existing_source else {
        return BTreeMap::new();
    };
    let extracted = extract_attribute_types(source);
    let mut out: BTreeMap<String, String> = BTreeMap::new();
    let data_name = &artifact.export.name;
    for attr in &artifact.attributes {
        let snake = to_snake_case(&attr.name);
        let key = ArtefactKey::data_attribute_type(data_name, &attr.name);
        let state = tracker.artefacts.get(&key).map(|e| e.state);
        if state == Some(ArtefactState::Fresh) {
            if let Some(ty) = extracted.get(&snake) {
                out.insert(snake.clone(), strip_multiplicity_wrap(ty));
            }
        }
    }
    out
}

/// Variant analogue of `attribute_types_from_tracker_and_source`. Walks the
/// existing `pub enum <Name>Payload { … }` block and recovers per-variant
/// attribute types; only `Fresh` `data_variant_attribute_type` tracker
/// entries are kept.
fn variant_attribute_types_from_tracker_and_source(
    artifact: &PreparedArtifact,
    tracker: &BuildTracker,
    existing_source: Option<&str>,
) -> BTreeMap<(String, String), String> {
    let mut out: BTreeMap<(String, String), String> = BTreeMap::new();
    let Some(source) = existing_source else {
        return out;
    };
    let extracted = extract_variant_attribute_types(source);
    let data_name = &artifact.export.name;
    for variant in &artifact.data_variants {
        for attr in &variant.attributes {
            let attr_snake = to_snake_case(&attr.name);
            let key = ArtefactKey::data_variant_attribute_type(
                data_name,
                &variant.name,
                &attr.name,
            );
            let state = tracker.artefacts.get(&key).map(|e| e.state);
            if state == Some(ArtefactState::Fresh) {
                if let Some(ty) = extracted.get(&(variant.name.clone(), attr_snake.clone())) {
                    out.insert(
                        (variant.name.clone(), attr_snake),
                        strip_multiplicity_wrap(ty),
                    );
                }
            }
        }
    }
    out
}

/// `extract_attribute_types` returns the *full* declared type, but the
/// `attribute_full_type` helper expects the *bare* type (it re-applies the
/// multiplicity wrap). Strip a leading `Vec<` and trailing `>` so the
/// roundtrip is idempotent.
fn strip_multiplicity_wrap(ty: &str) -> String {
    if let Some(inner) = ty.strip_prefix("Vec<").and_then(|s| s.strip_suffix('>')) {
        inner.to_string()
    } else {
        ty.to_string()
    }
}

fn generate_context_surgical(
    a: &PreparedArtifact,
    tracker: &BuildTracker,
    preserved: &BTreeMap<String, String>,
) -> String {
    let name = &a.export.name;
    let mut out = String::new();

    emit_data_type_imports(&mut out, &a.role_players);

    // Struct — regenerated wholesale
    writeln!(out, "pub struct {} {{", name).unwrap();
    for rp in &a.role_players {
        emit_role_player_field(&mut out, rp);
    }
    for prop in &a.props {
        writeln!(out, "    {}: (), // prop: {}", to_snake_case(&prop.name), prop.description).unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    // Impl
    writeln!(out, "impl {} {{", name).unwrap();

    // Functionalities
    for func in &a.functionalities {
        let key = ArtefactKey::functionality(name, &func.name);
        let method_name = to_snake_case(&func.name);
        let body = resolve_body(&key, &method_name, tracker, preserved);

        writeln!(out, "    /// {}", func.description.lines().next().unwrap_or("")).unwrap();
        // Receiver: prefer derived signature; otherwise inspect preserved
        // body. For derived signatures with parameters / non-unit return,
        // the helper renders the full shape.
        match func.derived_signature.as_ref() {
            Some(sig) => {
                emit_method_signature(&mut out, "pub", &method_name, Some(sig));
            }
            None => {
                let receiver = detect_receiver(&method_name, preserved);
                writeln!(out, "    pub fn {}({}) {{", method_name, receiver).unwrap();
            }
        }
        write!(out, "{}", body).unwrap();
        writeln!(out, "    }}").unwrap();
        writeln!(out).unwrap();
    }

    // Role methods
    for group in &a.role_methods {
        for rm in &group.methods {
            let key = ArtefactKey::role_method(name, &group.role, &rm.name);
            let body = resolve_body(&key, &rm.canonical_name, tracker, preserved);

            writeln!(out, "    /// Role method ({}.{}): {}", group.role, rm.name, rm.citation).unwrap();
            let receiver = detect_receiver(&rm.canonical_name, preserved);
            writeln!(
                out,
                "    fn {}({}, {}_: &{}) {{",
                rm.canonical_name,
                receiver,
                to_snake_case(&group.role),
                role_player_type(a, &group.role)
            )
            .unwrap();
            write!(out, "{}", body).unwrap();
            writeln!(out, "    }}").unwrap();
            writeln!(out).unwrap();
        }
    }

    writeln!(out, "}}").unwrap();
    out
}

fn generate_data_surgical(
    a: &PreparedArtifact,
    tracker: &BuildTracker,
    preserved: &BTreeMap<String, String>,
    preserved_attr_types: &BTreeMap<String, String>,
) -> String {
    let name = &a.export.name;
    let mut out = String::new();

    // Struct — regenerated wholesale, fields private. When the tracker says
    // an attribute's type is still `fresh`, the type from the previous
    // scaffold is preserved; otherwise the field reverts to `()` plus a
    // `// TODO: type to be filled by /implement` comment. STRUCT_MARKER on
    // the line above anchors `extract_attribute_types`.
    writeln!(out, "{}", STRUCT_MARKER).unwrap();
    writeln!(out, "pub struct {} {{", name).unwrap();
    for attr in &a.attributes {
        let preserved_ty = preserved_attr_types
            .get(&to_snake_case(&attr.name))
            .map(String::as_str);
        emit_attribute_field_with_preserved(&mut out, attr, preserved_ty);
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "impl {} {{", name).unwrap();

    // Constructor — parameter types match the struct field types so a
    // `Vec<…>` field takes a `Vec<…>` parameter. /implement still owns the
    // body.
    let new_params: Vec<String> = a.attributes.iter()
        .map(|attr| {
            let preserved_ty = preserved_attr_types
                .get(&to_snake_case(&attr.name))
                .map(String::as_str);
            format!(
                "{}: {}",
                to_snake_case(&attr.name),
                attribute_full_type(attr, preserved_ty),
            )
        })
        .collect();
    let constructor_key = ArtefactKey::data_constructor(name);
    let constructor_body = resolve_body(&constructor_key, "new", tracker, preserved);
    writeln!(out, "    /// Construct a new {}, validating every invariant from the prepared YAML.", name).unwrap();
    writeln!(out, "    pub fn new({}) -> anyhow::Result<Self> {{", new_params.join(", ")).unwrap();
    if constructor_body.trim() == "todo!()" || constructor_body.is_empty() {
        writeln!(out, "        todo!(\"enforce invariants and construct\")").unwrap();
    } else {
        write!(out, "{}", constructor_body).unwrap();
    }
    writeln!(out, "    }}").unwrap();
    writeln!(out).unwrap();

    // Getters — deterministic bodies. Return type tracks the field type so
    // `&self.<field>` typechecks for `Vec<T>` and bare `T` alike.
    for attr in &a.attributes {
        let preserved_ty = preserved_attr_types
            .get(&to_snake_case(&attr.name))
            .map(String::as_str);
        let field = to_snake_case(&attr.name);
        let ty = attribute_full_type(attr, preserved_ty);
        writeln!(out, "    /// {}", attr.description.lines().next().unwrap_or("")).unwrap();
        writeln!(out, "    pub fn {}(&self) -> &{} {{", field, ty).unwrap();
        writeln!(out, "        &self.{}", field).unwrap();
        writeln!(out, "    }}").unwrap();
        writeln!(out).unwrap();
    }

    // Operations — with_* (kind: with) emit by-value self returning Result<Self>;
    // others emit pub fn (&self).
    for op in &a.operations {
        let key = ArtefactKey::data_operation(name, &op.name);
        let method_name = to_snake_case(&op.name);
        let body = resolve_body(&key, &method_name, tracker, preserved);

        if op.kind.as_deref() == Some("with") {
            writeln!(out, "    /// {}", op.description.lines().next().unwrap_or("")).unwrap();
            writeln!(out, "    pub fn {}(self, value: ()) -> anyhow::Result<Self> {{", method_name).unwrap();
            if body.trim() == "todo!()" || body.is_empty() {
                writeln!(out, "        todo!(\"construct via Self::new with the field replaced\")").unwrap();
            } else {
                write!(out, "{}", body).unwrap();
            }
            writeln!(out, "    }}").unwrap();
            writeln!(out).unwrap();
        } else {
            writeln!(out, "    /// {}", op.description.lines().next().unwrap_or("")).unwrap();
            match op.derived_signature.as_ref() {
                Some(sig) => {
                    emit_method_signature(&mut out, "pub", &method_name, Some(sig));
                }
                None => {
                    let receiver = detect_receiver(&method_name, preserved);
                    writeln!(out, "    pub fn {}({}) {{", method_name, receiver).unwrap();
                }
            }
            write!(out, "{}", body).unwrap();
            writeln!(out, "    }}").unwrap();
            writeln!(out).unwrap();
        }
    }

    writeln!(out, "}}").unwrap();
    out
}

fn generate_projection_surgical(
    a: &PreparedArtifact,
    tracker: &BuildTracker,
    preserved: &BTreeMap<String, String>,
) -> String {
    // Surgical projection emission. Same shape as generate_projection but
    // resolves bodies from the tracker + preserved map so fresh entries keep
    // their existing implementation and stale entries reset to todo!().
    let name = &a.export.name;
    let mut out = String::new();

    emit_data_type_imports(&mut out, &a.role_players);

    // Struct — regenerated wholesale, private fields.
    writeln!(out, "pub struct {} {{", name).unwrap();
    for rp in &a.role_players {
        emit_role_player_field(&mut out, rp);
    }
    for prop in &a.props {
        writeln!(out, "    {}: (), // prop: {}", to_snake_case(&prop.name), prop.description).unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "impl {} {{", name).unwrap();

    // Constructor.
    if !a.role_players.is_empty() || !a.props.is_empty() {
        let params: Vec<String> = a.role_players.iter()
            .map(|rp| {
                let ty = role_player_field_type(rp);
                format!("{}: {}", to_snake_case(&rp.name), ty)
            })
            .chain(a.props.iter().map(|p| format!("{}: ()", to_snake_case(&p.name))))
            .collect();
        writeln!(out, "    /// Bind role players and props.").unwrap();
        writeln!(out, "    pub fn new({}) -> Self {{", params.join(", ")).unwrap();
        writeln!(out, "        todo!()").unwrap();
        writeln!(out, "    }}").unwrap();
        writeln!(out).unwrap();
    }

    // Functionalities — pub, always &self (immutable).
    for func in &a.functionalities {
        let key = ArtefactKey::projection_functionality(name, &func.name);
        let method_name = to_snake_case(&func.name);
        let body = resolve_body(&key, &method_name, tracker, preserved);

        writeln!(out, "    /// {}", func.description.lines().next().unwrap_or("")).unwrap();
        let sig = projection_safe_signature(func.derived_signature.as_ref());
        emit_method_signature(&mut out, "pub", &method_name, sig.as_ref());
        write!(out, "{}", body).unwrap();
        writeln!(out, "    }}").unwrap();
        writeln!(out).unwrap();
    }

    // Role methods — private, role player as & (never &mut).
    for group in &a.role_methods {
        for rm in &group.methods {
            let key = ArtefactKey::projection_role_method(name, &group.role, &rm.name);
            let body = resolve_body(&key, &rm.canonical_name, tracker, preserved);

            writeln!(out, "    /// Role method ({}.{}): {}", group.role, rm.name, rm.citation).unwrap();
            writeln!(
                out,
                "    fn {}(&self, {}_: &{}) {{",
                rm.canonical_name,
                to_snake_case(&group.role),
                role_player_type(a, &group.role)
            )
            .unwrap();
            write!(out, "{}", body).unwrap();
            writeln!(out, "    }}").unwrap();
            writeln!(out).unwrap();
        }
    }

    writeln!(out, "}}").unwrap();
    out
}

/// Decide whether to preserve an existing body or emit `todo!()`.
fn resolve_body(
    key: &ArtefactKey,
    method_name: &str,
    tracker: &BuildTracker,
    preserved: &BTreeMap<String, String>,
) -> String {
    let state = tracker
        .artefacts
        .get(key)
        .map(|e| e.state);

    match state {
        Some(ArtefactState::Fresh) => {
            // Preserve the existing body if we have it
            if let Some(body) = preserved.get(method_name) {
                body.clone()
            } else {
                "        todo!()\n".to_string()
            }
        }
        Some(ArtefactState::Stale) | Some(ArtefactState::NotImplemented) | None => {
            "        todo!()\n".to_string()
        }
    }
}

/// Detect the receiver (`&self` or `&mut self`) from preserved method source.
/// Falls back to `&self` if not found.
fn detect_receiver(method_name: &str, preserved: &BTreeMap<String, String>) -> &'static str {
    if preserved.contains_key(method_name) {
        // Check if the preserved method was using &mut self
        // We rely on a convention: if the body was preserved, we check the
        // receiver_hints map which is populated during extraction.
        // For now, default to &self — the implementer upgrades as needed.
        "&self"
    } else {
        "&self"
    }
}

/// Extract method bodies from existing Rust source code.
///
/// Returns a map from method name → body text (the lines between the opening
/// `{` and closing `}` of the method, preserving exact formatting).
///
/// This is a text-based extractor that handles our generated code format
/// reliably. It does NOT use syn for body extraction to avoid pretty-printing
/// drift.
pub fn extract_method_bodies_from_source(source: &str) -> BTreeMap<String, String> {
    extract_method_bodies(source)
}

/// Locate the byte offset of the data-struct block in `source` — the
/// position from which a forward `find('{')` will land on the struct's
/// opening brace. Prefers the explicit [`STRUCT_MARKER`] anchor; falls
/// back to the literal `"pub struct "` for pre-marker source files.
fn locate_struct_block(source: &str) -> Option<usize> {
    if let Some(marker_pos) = source.find(STRUCT_MARKER) {
        // After the marker line, the next `pub struct` opens the block.
        let after_marker = marker_pos + STRUCT_MARKER.len();
        if let Some(rel) = source[after_marker..].find("pub struct ") {
            return Some(after_marker + rel);
        }
    }
    // Legacy fallback — TODO: remove after every project has been
    // re-scaffolded with the marker. The fallback ensures a tracker
    // populated against an older scaffold continues to recover types.
    source.find("pub struct ")
}

/// Locate the byte offset of the payload-enum block in `source`. Prefers
/// the explicit [`PAYLOAD_ENUM_MARKER`] anchor; falls back to the literal
/// `"Payload {"` substring for pre-marker source files.
fn locate_payload_enum_block(source: &str) -> Option<usize> {
    if let Some(marker_pos) = source.find(PAYLOAD_ENUM_MARKER) {
        let after_marker = marker_pos + PAYLOAD_ENUM_MARKER.len();
        if let Some(rel) = source[after_marker..].find("pub enum ") {
            return Some(after_marker + rel);
        }
    }
    // Legacy fallback — TODO: remove after every project has been
    // re-scaffolded with the marker.
    source.find("Payload {")
}

/// Parse the first variant-data payload-enum block in `source` and return
/// `(variant_snake, attribute_snake) -> rust_type` for every named-field
/// variant. Used by the surgical data emitter to preserve `/implement`-chosen
/// types for variant attributes across re-scaffolds.
///
/// Anchoring rule: prefer [`PAYLOAD_ENUM_MARKER`] (the explicit anchor
/// codegen emits today). Fall back to the literal `"Payload {"` substring
/// for pre-marker source files — TODO: remove the fallback once every
/// downstream project has been re-scaffolded after the marker rollout.
pub fn extract_variant_attribute_types(source: &str) -> BTreeMap<(String, String), String> {
    let mut out: BTreeMap<(String, String), String> = BTreeMap::new();
    let Some(payload_start) = locate_payload_enum_block(source) else {
        return out;
    };
    // Anchor on the marker (or legacy "Payload {" fallback); walk forward to
    // the first opening brace, then walk variants until the matching closing
    // brace.
    let after = &source[payload_start..];
    let Some(brace_open) = after.find('{') else {
        return out;
    };
    let bytes = after.as_bytes();
    let mut idx = brace_open + 1;
    let mut depth = 1i32;
    while idx < bytes.len() && depth > 0 {
        match bytes[idx] {
            b'{' => depth += 1,
            b'}' => depth -= 1,
            _ => {}
        }
        if depth == 0 {
            break;
        }
        idx += 1;
    }
    let body = &after[brace_open + 1..idx];

    // Walk lines, tracking the current variant name. A line beginning with a
    // PascalCase identifier opens a variant; if it ends with `{`, named-field
    // form follows.
    let mut current_variant: Option<String> = None;
    let mut variant_depth = 0i32;
    for raw in body.lines() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with("//") {
            continue;
        }
        // A new top-level variant declaration.
        if variant_depth == 0 {
            // `Name {` or `Name,` or `Name`. Strip trailing `,` / `{`.
            let trimmed = line.trim_end_matches(['{', ',']).trim();
            if trimmed.is_empty() {
                continue;
            }
            // First word should be a PascalCase identifier.
            let first = trimmed.split_whitespace().next().unwrap_or("");
            if first.chars().next().map(|c| c.is_ascii_uppercase()).unwrap_or(false) {
                current_variant = Some(pascal_to_snake(first));
                if line.ends_with('{') {
                    variant_depth = 1;
                }
                continue;
            }
        } else {
            // Inside a named-field variant body.
            if line == "}," || line == "}" {
                variant_depth -= 1;
                if variant_depth == 0 {
                    current_variant = None;
                }
                continue;
            }
            // `name: Type,` line.
            let cleaned = line
                .split_once("//")
                .map(|(b, _)| b.trim_end())
                .unwrap_or(line)
                .trim_end_matches(',')
                .trim();
            let Some((field, ty)) = cleaned.split_once(':') else {
                continue;
            };
            let field = field.trim();
            let ty = ty.trim();
            if field.is_empty() || ty.is_empty() {
                continue;
            }
            if !field.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
                continue;
            }
            if let Some(variant) = current_variant.as_ref() {
                out.insert((variant.clone(), field.to_string()), ty.to_string());
            }
        }
    }
    out
}

/// Convert a PascalCase identifier to snake_case. `UserUtterance` →
/// `user_utterance`; `ConfirmationCardRejected` →
/// `confirmation_card_rejected`. Used by the variant-payload extractor to
/// match enum variant identifiers back to the snake-cased names in the
/// prepared YAML.
pub fn pascal_to_snake(name: &str) -> String {
    let mut out = String::with_capacity(name.len() + 4);
    for (i, c) in name.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

/// Extract `field_name -> rust_type` for the first data struct block in
/// `source`. Used by surgical data emitters to preserve the per-attribute
/// Rust type chosen by `/implement` across re-scaffolds. The bracket-balanced
/// scan stops at the matching `}` so nested inline tuple types parse cleanly.
///
/// Anchoring rule: prefer [`STRUCT_MARKER`] (the explicit anchor codegen
/// emits today). Fall back to the literal `"pub struct "` substring for
/// pre-marker source files — TODO: remove the fallback once every
/// downstream project has been re-scaffolded after the marker rollout.
pub fn extract_attribute_types(source: &str) -> BTreeMap<String, String> {
    let mut out: BTreeMap<String, String> = BTreeMap::new();
    let Some(struct_start) = locate_struct_block(source) else {
        return out;
    };
    let after = &source[struct_start..];
    let Some(brace_open) = after.find('{') else {
        return out;
    };
    // Find the matching closing brace.
    let mut depth = 1i32;
    let mut idx = brace_open + 1;
    let bytes = after.as_bytes();
    while idx < bytes.len() && depth > 0 {
        match bytes[idx] {
            b'{' => depth += 1,
            b'}' => depth -= 1,
            _ => {}
        }
        if depth == 0 {
            break;
        }
        idx += 1;
    }
    let body = &after[brace_open + 1..idx];

    for raw in body.lines() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with("//") {
            continue;
        }
        // Strip trailing comma + inline `// ...` comment.
        let no_comment = match line.split_once("//") {
            Some((before, _)) => before.trim_end(),
            None => line,
        };
        let no_comma = no_comment.trim_end_matches(',').trim();
        // Field declarations look like `name: Type` (the first `:` separates).
        let Some((name, ty)) = no_comma.split_once(':') else {
            continue;
        };
        let name = name.trim();
        let ty = ty.trim();
        // `pub` prefix would only appear on tuple-struct-y things; data
        // emitters never emit `pub` on fields, so skip if seen.
        let name = name.strip_prefix("pub ").unwrap_or(name);
        if name.is_empty() || ty.is_empty() {
            continue;
        }
        // Only capture identifier-looking field names (rules out anything
        // weird in a comment or doc block).
        if !name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
            continue;
        }
        out.insert(name.to_string(), ty.to_string());
    }
    out
}

fn extract_method_bodies(source: &str) -> BTreeMap<String, String> {
    let mut bodies = BTreeMap::new();
    let lines: Vec<&str> = source.lines().collect();
    let mut i = 0;

    while i < lines.len() {
        // Look for method declarations: `    pub fn name(` or `    fn name(`
        let trimmed = lines[i].trim();
        let is_method = (trimmed.starts_with("pub fn ") || trimmed.starts_with("fn "))
            && trimmed.contains('(')
            && trimmed.ends_with('{');

        if is_method {
            // Extract method name
            let name_start = if trimmed.starts_with("pub fn ") {
                "pub fn ".len()
            } else {
                "fn ".len()
            };
            let name_end = trimmed[name_start..].find('(').unwrap_or(0) + name_start;
            let method_name = &trimmed[name_start..name_end];

            // Skip `todo!()` only methods — no need to preserve them
            if i + 1 < lines.len() && i + 2 < lines.len() {
                let next = lines[i + 1].trim();
                let after = lines[i + 2].trim();
                if next == "todo!()" && after == "}" {
                    i += 3;
                    continue;
                }
            }

            // Extract body: everything between opening `{` and the matching `}`
            let mut body = String::new();
            let mut depth = 1;
            let mut j = i + 1;

            while j < lines.len() && depth > 0 {
                let line = lines[j];
                // Count braces to find the matching closing brace
                for ch in line.chars() {
                    match ch {
                        '{' => depth += 1,
                        '}' => depth -= 1,
                        _ => {}
                    }
                }
                if depth > 0 {
                    body.push_str(line);
                    body.push('\n');
                }
                j += 1;
            }

            if !body.is_empty() {
                bodies.insert(method_name.to_string(), body);
            }
            i = j;
        } else {
            i += 1;
        }
    }

    bodies
}

